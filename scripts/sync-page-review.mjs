// MCP-SERVER-1 (log §418): the Chrome extension's page review, shared with
// the MCP tool `revisar_pagina`. The extension's files are the source of
// truth; this script writes the server copies, and
// `lib/page-review/sync.test.ts` fails whenever they drift.
//
//   node scripts/sync-page-review.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const EXT = join(root, "docs/chrome-extension/prueba/extension");
const OUT = join(root, "lib/page-review");

export function buildCollectFactory(collectSource) {
  // The extension runs collectPageFacts inside the tab, against the tab's
  // globals. On the server those globals are passed in per call, so the
  // function closes over parameters instead of `globalThis` and two
  // concurrent reviews never share a document.
  const body = collectSource.replace(/\nif \(typeof module !== "undefined"\) module\.exports = \{ collectPageFacts \};\s*$/, "\n");
  return (
    "/* GENERATED by scripts/sync-page-review.mjs from docs/chrome-extension/prueba/extension/collect.js. Do not edit. */\n" +
    "module.exports = function makeCollectPageFacts(document, location, fetch, performance, DOMParser, Node) {\n" +
    body +
    "return collectPageFacts;\n};\n"
  );
}

export function buildScoreCopy(scoreSource) {
  return "/* GENERATED by scripts/sync-page-review.mjs from docs/chrome-extension/prueba/extension/score.js. Do not edit. */\n" + scoreSource;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(join(OUT, "collect.cjs"), buildCollectFactory(readFileSync(join(EXT, "collect.js"), "utf8")));
  writeFileSync(join(OUT, "score.cjs"), buildScoreCopy(readFileSync(join(EXT, "score.js"), "utf8")));
  console.log("lib/page-review/{collect,score}.cjs written");
}
